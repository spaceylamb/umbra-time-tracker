"""Recover the sentence a human actually wrote, from an AI conversation log.

Both local jsonl files and Butler's tasks.prompt mix machine-injected content
with user input, and nothing in the fields distinguishes them — both are
type=user, both are prompt. Three shapes:

  1. purely machine-generated  "You are the REDUCE agent for a batch..."
     → drop the whole record
  2. injected prefix + real task  "⚠️ IMPORTANT—you are running in an isolated
     worktree...\\n\\n<the real task>"      → strip the prefix
  3. injected wrapper + real question  "The user is reading a page in their
     knowledge base...\\nQuestion: <the real one>\\nRequirements: ..."
                                            → extract the question

⚠️ An earlier implementation dropped shapes 2 and 3 entirely, which threw away
   real data. What follows 2000 characters of worktree preamble — "create entity
   pages for two filmmakers" — *is* the intent of that task.
"""

import re

# Purely machine-generated: no user intent anywhere in it.
MACHINE_ONLY = re.compile(
    r"^(You are the \w+ agent"
    r"|\[Request interrupted by user"
    r"|Continue from where you left off\."
    r"|This session is being continued from a previous conversation"
    r"|Caveat: The messages below were generated by the user while running"
    r"|Base directory for this skill:)",
    re.I,
)

# Injected prefix: the first paragraph is a runtime warning to the agent; the
# real task begins after the blank line.
PREFIX_THEN_TASK = re.compile(
    r"^(⚠️\s*重要——你运行在一个隔离的 git worktree"
    r"|⚠️\s*IMPORTANT[—-]+you are running in an isolated git worktree)")

# Markers for user content. Injected templates get long (2000 characters has
# been observed) and the human sentence can sit at the start, middle or end —
# so extraction is by **marker**, never by position. Order is priority.
#
# The patterns stay bilingual on purpose: they match the user's own logs, not
# this repo. Add your own agent harness's markers here.
USER_MARKERS = (
    # "User message: <the real thing>" — through to the end
    re.compile(r"(?:用户消息|User message)[:：]\s*(?P<u>.+)\s*$", re.S | re.I),
    # "Question: <the real one>" — up to a blank line or "Requirements:"
    re.compile(r"(?:问题|Question)[:：]\s*(?P<u>.+?)"
               r"(?:\n\s*\n|\n(?:要求|Requirements)[:：]|$)", re.S | re.I),
)

# The knowledge-base assistant's wrapper.
VAULT_WRAPPER = re.compile(r"^(用户正在读知识库里的页面"
                           r"|The user is reading a page in their knowledge base)")


def _extract_marked(text: str) -> str | None:
    for pat in USER_MARKERS:
        m = pat.search(text)
        if m:
            found = m.group("u").strip()
            if found:
                return found
    return None


def clean(text: str) -> str | None:
    """The content the user actually wrote; None for purely machine text."""
    text = (text or "").strip()
    if not text or text.startswith("<"):
        return None
    if MACHINE_ONLY.match(text):
        return None

    # Explicit markers win — they are the most reliable signal, unaffected by
    # how long or how differently structured the template becomes.
    marked = _extract_marked(text)
    if marked:
        return marked

    if PREFIX_THEN_TASK.match(text):
        # First paragraph is the runtime warning, the task follows. No second
        # paragraph means this record is warning and nothing else.
        _, _, rest = text.partition("\n\n")
        return rest.strip() or None

    if VAULT_WRAPPER.match(text):
        # The wrapper is present but no user marker was found — the whole
        # record is template, with no user content in it.
        return None

    return text
